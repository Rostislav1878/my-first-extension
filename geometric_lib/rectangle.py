def area(a, b):
    '''
    Принимает длины сторон прямоугольника: a и b. Возвращает площадь этого прямоугольника.
    
    Пример вызова:
    area(4, 12) == 48
    '''
    return a * b

def perimeter(a, b):
    '''
    Принимает длины сторон прямоугольника: a и b. Возвращает периметр этого прямоугольника.
    
    Пример вызова:
    perimeter(4, 12) == 32
    '''
    return 2 * (a + b)