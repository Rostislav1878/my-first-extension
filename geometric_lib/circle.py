import math


def area(r):
    '''
    Принимает радиус круга: r. Возвращает площадь этого круга.
    
    Пример вызова:
    area(8) == 201.06192982975
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает радиус круга: r. Возвращает длину окружности (периметр) этого круга.

    Пример вызова:
    perimeter(8) == 50.265482457437
    '''
    return 2 * math.pi * r
